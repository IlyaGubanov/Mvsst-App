#!/usr/bin/env bash
# =====================================================================
#  Обновление приложения на сервере Linux до последней версии из GitHub.
#
#  Запуск:  bash /var/www/mvs/mvs-app/deploy/update.sh
#
#  По шагам: копия базы → забрать код → библиотеки сервера → изменения структуры базы →
#  собрать интерфейс → перезапустить сервер. Если какой-то шаг упал — скрипт остановится,
#  а работающая версия продолжит работать (кроме случая, когда упала миграция — см. журнал).
# =====================================================================

set -euo pipefail

APP="$(cd "$(dirname "$0")/.." && pwd)"   # папка mvs-app (на уровень выше deploy/)

echo "1/6 Резервная копия базы"
bash "$APP/deploy/backup.sh"

echo "2/6 Забираем новый код"
cd "$APP"
git pull --ff-only                       # только «перемотка вперёд»: если на сервере правили файлы руками — остановится

echo "3/6 Библиотеки сервера"
cd "$APP/server"
npm ci --omit=dev

echo "4/6 Изменения структуры базы"
npm run migrate

echo "5/6 Сборка интерфейса"
cd "$APP/client"
npm ci
npm run build

echo "6/6 Перезапуск сервера"
pm2 reload mvs-api

echo "Готово. Проверка: curl -s http://127.0.0.1:3000/api/health"
curl -s http://127.0.0.1:3000/api/health; echo
